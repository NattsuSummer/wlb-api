import { hashPassword } from '../src/crypto';

export interface SeedUser {
  username: string;
  displayName?: string;
  role?: 'admin' | 'member';
  avatarColor?: string;
  targets?: Record<string, number>;
  slots?: { weekday: number; hour: number; categories: string[]; description?: string }[];
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

/**
 * SQL statements (one per line) that insert the seed users, targets and slots.
 * Safe to run twice: existing rows are left untouched (INSERT OR IGNORE).
 * Seeded users must change their password on first login.
 */
export async function buildSeedSql(seed: { users: SeedUser[] }, password: string): Promise<string> {
  const out: string[] = ['-- generated by scripts/build-seed-sql.ts'];
  for (const u of seed.users) {
    const name = u.username.toLowerCase();
    const uid = `(SELECT id FROM users WHERE username = ${q(name)})`;
    out.push(
      `INSERT OR IGNORE INTO users (username, display_name, password_hash, role, avatar_color, must_change_password) VALUES (${q(name)}, ${q(u.displayName ?? name)}, ${q(await hashPassword(password))}, ${q(u.role ?? 'member')}, ${u.avatarColor ? q(u.avatarColor) : 'NULL'}, 1);`,
    );
    for (const [cat, pct] of Object.entries(u.targets ?? {})) {
      out.push(`INSERT OR IGNORE INTO user_category_targets (user_id, category_id, pct) SELECT ${uid}, id, ${Math.round(pct)} FROM time_categories WHERE name_th = ${q(cat)};`);
    }
    for (const s of u.slots ?? []) {
      out.push(`INSERT OR IGNORE INTO schedule_slots (user_id, weekday, hour, description) VALUES (${uid}, ${s.weekday}, ${s.hour}, ${q(s.description ?? '')});`);
      for (const cat of s.categories) {
        out.push(
          `INSERT OR IGNORE INTO schedule_slot_categories (slot_id, category_id) SELECT s.id, c.id FROM schedule_slots s, time_categories c WHERE s.user_id = ${uid} AND s.weekday = ${s.weekday} AND s.hour = ${s.hour} AND c.name_th = ${q(cat)};`,
        );
      }
    }
  }
  return out.join('\n') + '\n';
}
